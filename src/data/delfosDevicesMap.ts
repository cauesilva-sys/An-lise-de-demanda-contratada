export function findDelfosDeviceIdByName(name: string): number | null {
  const norm = (str: string) =>
    str
      .toLowerCase()
      .normalize('NFD')
      .replace(/[\u0300-\u036f]/g, '')
      .replace(/[^a-z0-9]/g, ' ')
      .replace(/\s+/g, ' ')
      .trim();

  const n = norm(name);

  // 1. Specific aliases & Roman numeral disambiguation
  if (/\buruguaiana\s*(1|i)\b/i.test(n) && !/\buruguaiana\s*(ii|iii|iv)\b/i.test(n)) return 20001;
  if (/\buruguaiana\s*(2|ii)\b/i.test(n)) return 2257;
  if (/\buruguaiana\s*(4|iv)\b/i.test(n)) return 2256;
  if (n.includes('presidente alves')) return 1394;
  if (n.includes('taubate')) return 1041;
  if (n.includes('canas')) return 1393;
  if (n.includes('barretos')) return 1160;

  // Salto de Pirapora disambiguation
  if (n.includes('salto de pirapora')) {
    if (n.includes('1') || n.includes(' i') || n.endsWith('1')) return 1389;
    if (n.includes('2') || n.includes(' ii') || n.endsWith('2')) return 1390;
    if (n.includes('3') || n.includes(' iii') || n.endsWith('3')) return 1391;
    if (n.includes('4') || n.includes(' iv') || n.endsWith('4')) return 1392;
  }

  // Leopoldo Bulhões
  if (n.includes('leopoldo')) {
    if (n.includes('1') || n.includes('01')) return 24909;
    if (n.includes('2') || n.includes('02')) return 24910;
  }

  // Caracará
  if (n.includes('caracara')) {
    if (n.includes('1') || n.includes(' i') || n.endsWith('1')) return 24192;
    if (n.includes('2') || n.includes(' ii') || n.endsWith('2')) return 24193;
    if (n.includes('3') || n.includes(' iii') || n.endsWith('3')) return 24194;
  }

  // Luis Eduardo Magalhães
  if (n.includes('eduardo magalhaes i ') || n.includes('eduardo magalhaes 1 ')) {
    if (n.includes('1') || n.includes('01')) return 3651;
    if (n.includes('2') || n.includes('02')) return 3649;
    if (n.includes('3') || n.includes('03')) return 3650;
  }
  if (n.includes('eduardo magalhaes ii') || n.includes('eduardo magalhaes 2')) {
    if (n.includes('4') || n.includes('04')) return 31471;
    if (n.includes('5') || n.includes('05')) return 31472;
    if (n.includes('6') || n.includes('06')) return 31473;
  }

  const toArabic = (s: string) =>
    s
      .replace(/\bufv01\b|\bufv 01\b|\bufv 1\b/g, '1')
      .replace(/\bufv02\b|\bufv 02\b|\bufv 2\b/g, '2')
      .replace(/\bufv03\b|\bufv 03\b|\bufv 3\b/g, '3')
      .replace(/\bufv04\b|\bufv 04\b|\bufv 4\b/g, '4')
      .replace(/\bufv05\b|\bufv 05\b|\bufv 5\b/g, '5')
      .replace(/\bufv06\b|\bufv 06\b|\bufv 6\b/g, '6')
      .replace(/\s+i\b/g, ' 1')
      .replace(/\s+ii\b/g, ' 2')
      .replace(/\s+iii\b/g, ' 3')
      .replace(/\s+iv\b/g, ' 4')
      .replace(/\s+v\b/g, ' 5')
      .replace(/\s+vi\b/g, ' 6')
      .replace(/\s+/g, ' ')
      .trim();

  const nArabic = toArabic(n);

  // 2. Exact match on normalized or arabic
  for (const d of DELFOS_SOLAR_FIELDS) {
    const dn = norm(d.name);
    const dnArabic = toArabic(dn);
    if (dn === n || dnArabic === nArabic) return d.id;
  }

  // 3. Substring match
  for (const d of DELFOS_SOLAR_FIELDS) {
    const dn = norm(d.name);
    const dnArabic = toArabic(dn);
    if (dn.includes(n) || n.includes(dn) || dnArabic.includes(nArabic) || nArabic.includes(dnArabic)) {
      return d.id;
    }
  }

  return null;
}
